    #[test]
    fn hysteresis_holds_likely_until_exit_threshold() {
        let predictor = BridgePredictor::default();
        let now = scheduled_now();
        let strong = evidence(
            "ais-strong",
            "local-ais",
            now,
            BridgeObservation::AisTrack {
                mmsi: None,
                vessel_name: None,
                movement: VesselMovement::Approaching,
                route_intersects: true,
                eta: Some(EtaRangeMinutes::new(8, 10)),
                opening_propensity: Some(Confidence::CERTAIN),
            },
        );
        let mut corroborating = evidence(
            "upstream-strong",
            "fl511",
            now,
            BridgeObservation::OutboundProgress {
                bridge: "Miami Avenue Bridge".into(),
                stage: OutboundProgressStage::High,
                eta: Some(EtaRangeMinutes::new(9, 12)),
            },
        );
        corroborating.reliability = Confidence::from_basis_points(3_500);
        let previous = predictor
            .evaluate(now, &[strong, corroborating], None)
            .expect("initial prediction");
        assert_eq!(previous.state, BridgeState::Likely);

        let mut weaker = evidence(
            "ais-weaker",
            "local-ais",
            now,
            BridgeObservation::AisTrack {
                mmsi: None,
                vessel_name: None,
                movement: VesselMovement::Approaching,
                route_intersects: true,
                eta: Some(EtaRangeMinutes::new(8, 10)),
                opening_propensity: Some(Confidence::CERTAIN),
            },
        );
        weaker.reliability = Confidence::from_basis_points(8_200);
        let held = predictor
            .evaluate(now, &[weaker], Some(&previous))
            .expect("hysteresis prediction");

        assert!(held.confidence.as_score() < predictor.config().thresholds.likely.enter);
        assert!(held.confidence.as_score() >= predictor.config().thresholds.likely.exit);
        assert_eq!(held.state, BridgeState::Likely);
        assert!(held.transition.held_by_hysteresis);
    }

    #[test]
    fn contribution_is_halved_at_its_half_life() {
        let predictor = BridgePredictor::default();
        let now = scheduled_now();
        let observed = TimestampMillis::new(
            now.0 - i64::from(predictor.config().decay.ais.half_life_seconds) * 1_000,
        );
        let ais = evidence(
            "ais-half-life",
            "local-ais",
            observed,
            BridgeObservation::AisTrack {
                mmsi: None,
                vessel_name: None,
                movement: VesselMovement::Approaching,
                route_intersects: true,
                eta: Some(EtaRangeMinutes::new(8, 10)),
                opening_propensity: Some(Confidence::CERTAIN),
            },
        );
        let prediction = predictor.evaluate(now, &[ais], None).expect("prediction");
        let contribution = prediction
            .contributions
            .iter()
            .find(|item| item.kind == EvidenceKind::Ais)
            .expect("AIS contribution");
        assert!((contribution.freshness_factor - 0.5).abs() < 0.001);
        assert!((contribution.applied_score - contribution.raw_weight * 0.5).abs() < 0.001);
    }
