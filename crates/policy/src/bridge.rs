    fn millis(text: &str) -> TimestampMillis {
        let timestamp: Timestamp = text.parse().expect("valid timestamp");
        TimestampMillis::new(timestamp.as_millisecond())
    }

    fn evidence(
        id: &str,
        source: &str,
        at: TimestampMillis,
        fact: BridgeObservation,
    ) -> BridgeEvidence {
        BridgeEvidence {
            observation_id: ObservationId::from(id),
            source_id: SourceId::from(source),
            observed_at: at,
            expires_at: None,
            availability: AvailabilityStatus::Live,
            reliability: Confidence::CERTAIN,
            fact,
        }
    }

    fn scheduled_now() -> TimestampMillis {
        millis("2026-08-14T19:10:00Z") // Friday 15:10 EDT, scheduled mode.
    }

    #[test]
    fn schedule_alone_does_not_create_a_prediction() {
        let prediction = BridgePredictor::default()
            .evaluate(scheduled_now(), &[], None)
            .expect("prediction");
        assert_eq!(prediction.state, BridgeState::Clear);
        assert_eq!(prediction.urgency, Urgency::Passive);
        assert_eq!(prediction.availability.status, AvailabilityStatus::Degraded);
    }

    #[test]
    fn runtime_strength_ais_plus_upstream_crosses_likely_threshold() {
        let now = scheduled_now();
        let mut ais = evidence(
            "ais-1",
            "local-ais",
            now,
            BridgeObservation::AisTrack {
                mmsi: Some("367000001".into()),
                vessel_name: Some("Test Vessel".into()),
                movement: VesselMovement::Approaching,
                route_intersects: true,
                eta: Some(EtaRangeMinutes::new(8, 12)),
                opening_propensity: None,
            },
        );
        ais.reliability = Confidence::from_basis_points(8_500);
        let mut upstream = evidence(
            "fl511-upstream",
            "fl511",
            now,
            BridgeObservation::OutboundProgress {
                bridge: "SW 2 Avenue".into(),
                stage: OutboundProgressStage::High,
                eta: Some(EtaRangeMinutes::new(9, 14)),
            },
        );
        upstream.reliability = Confidence::from_basis_points(3_500);
        let prediction = BridgePredictor::default()
            .evaluate(now, &[ais, upstream], None)
            .expect("prediction");

        assert_eq!(prediction.state, BridgeState::Likely);
        assert_eq!(prediction.eta, Some(EtaRangeMinutes::new(8, 12)));
        assert!(prediction.confidence.as_score() >= 0.58);
    }

